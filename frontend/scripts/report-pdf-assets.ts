// Development only: assets in the backend JAR never read frontend files at runtime.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { tokens } from '../../docs/design-system/tokens.ts'
const root = new URL('../../', import.meta.url)
const target = new URL('backend/src/main/resources/report-pdf/', root)
const hashes = ['docs/design-system/tokens.ts', 'frontend/public/favicon.svg',
  ...['brand.png', 'Figtree-Regular.ttf', 'Figtree-Bold.ttf', 'OFL.txt'].map(name => `backend/src/main/resources/report-pdf/${name}`)]
const text = `# Generated by frontend/scripts/report-pdf-assets.ts\nink=${tokens.text.primary}\nmuted=${tokens.text.secondary}\naccent=${tokens.brand.accent}\nline=${tokens.border.subtle}\n` + hashes.map(path => `# sha256 ${path} ${createHash('sha256').update(readFileSync(new URL(path, root))).digest('hex')}\n`).join('')
const output = new URL('brand.properties', target)
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== text) throw new Error('PDF assets differ: regenerate brand.png from favicon.svg, review fonts and run report-pdf-assets.ts')
} else {
  writeFileSync(fileURLToPath(output), text)
}
